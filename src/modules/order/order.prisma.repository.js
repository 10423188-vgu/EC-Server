import { prisma } from "../../configs/db/index.js";
import { performance } from "node:perf_hooks";
import { logger } from "../../shared/utils/logger.js";
import { buildOverdueOrderWhere, ORDER_SLA_HOURS } from "./order.policy.js";

const ORDER_INCLUDE = {
  items: true,
  payment: {
    select: {
      method: true,
      status: true,
      amount: true,
      refundedAmount: true,
      transferContent: true,
      confirmedBy: true,
      confirmedByUser: { select: { id: true, name: true, role: true } },
      paidAt: true,
    },
  },
  returnRequests: {
    orderBy: { createdAt: "desc" },
    include: { items: true },
  },
};

// why: OrdersPage only ever renders the first 2 items per card (ORDER_CARD_VISIBLE_ITEMS)
// and trims the rest client-side — list endpoints don't need the full items array, only
// detail does. _count.items feeds itemsCount so the "+N more" badge still counts correctly.
const ORDER_LIST_INCLUDE = {
  ...ORDER_INCLUDE,
  items: { take: 2 },
  returnRequests: { ...ORDER_INCLUDE.returnRequests, take: 1 },
  _count: { select: { items: true } },
};

// why: the admin table needs counts and action eligibility, not item bodies,
// shipping snapshots or confirming-user joins. Detail keeps the full shape.
const ADMIN_ORDER_SELECT = {
  id: true,
  status: true,
  createdAt: true,
  total: true,
  user: { select: { id: true, name: true, email: true } },
  payment: {
    select: { method: true, status: true, amount: true, refundedAmount: true },
  },
  returnRequests: {
    select: { id: true, status: true, refundAmount: true },
    orderBy: { createdAt: "desc" },
    take: 1,
  },
  _count: { select: { items: true } },
};

const withAdminListShape = ({ _count, ...order }) => ({
  ...order,
  itemsCount: _count.items,
});

// why: Order carries its own shipping snapshot (captured at checkout) instead of
// joining the live Address — reshape it into the same `address` shape the client
// already expects, so editing/deleting the saved Address never rewrites past orders.
// itemsCount falls back to items.length for detail queries, which load every item
// and never request _count.
const withAddressShape = (order) =>
  order && {
    ...order,
    itemsCount: order._count?.items ?? order.items.length,
    address: {
      fullName: order.shippingFullName,
      phone: order.shippingPhone,
      street: order.shippingStreet,
      ward: order.shippingWard,
      district: order.shippingDistrict,
      city: order.shippingCity,
      postalCode: order.shippingPostalCode,
      countryCode: order.shippingCountryCode,
    },
  };

// why: only orders that actually got paid count toward a user's spend/tier — PENDING,
// AWAITING_PAYMENT, CANCELLED and REFUNDED never collected money
const SPENT_STATUSES = [
  "PAID",
  "PROCESSING",
  "SHIPPED",
  "OUT_FOR_DELIVERY",
  "DELIVERED",
];
const ORDER_STATUSES = [
  "PENDING",
  "AWAITING_PAYMENT",
  "PAID",
  "PROCESSING",
  "SHIPPED",
  "OUT_FOR_DELIVERY",
  "DELIVERED",
  "CANCELLED",
  "REFUNDED",
];

const buildAdminWhere = ({
  status,
  paymentStatus,
  search,
  dateFrom,
  dateTo,
  overdue,
}) => {
  const where = {};
  if (status) where.status = status;
  if (paymentStatus) where.payment = { is: { status: paymentStatus } };
  if (dateFrom || dateTo) {
    where.createdAt = {
      ...(dateFrom && { gte: dateFrom }),
      ...(dateTo && { lte: dateTo }),
    };
  }
  if (search) {
    where.OR = [
      { id: { startsWith: search, mode: "insensitive" } },
      { user: { is: { name: { contains: search, mode: "insensitive" } } } },
      { user: { is: { email: { contains: search, mode: "insensitive" } } } },
    ];
  }
  return overdue ? { AND: [where, buildOverdueOrderWhere()] } : where;
};

export const orderPrismaRepository = {
  // why: id is generated by the caller (not left to Prisma's default) so paymentMethod-specific
  // fields like transferContent can be derived from it and written in this same insert —
  // no follow-up UPDATE round-trip needed once the order/payment rows already exist
  create: (
    {
      id,
      userId,
      idempotencyKey,
      addressId,
      shippingFullName,
      shippingPhone,
      shippingStreet,
      shippingWard,
      shippingDistrict,
      shippingCity,
      shippingPostalCode,
      shippingCountryCode,
      subtotal,
      shippingFee,
      discountAmount,
      total,
      status,
      note,
      couponId,
      couponCode,
      items,
      paymentMethod,
      paymentStatus,
      transferContent,
    },
    tx = null,
  ) => {
    const run = async (dbTx) => {
      const order = await dbTx.order.create({
        data: {
          id,
          userId,
          idempotencyKey: idempotencyKey ?? null,
          addressId,
          shippingFullName,
          shippingPhone,
          shippingStreet,
          shippingWard,
          shippingDistrict,
          shippingCity,
          shippingPostalCode,
          shippingCountryCode,
          subtotal,
          shippingFee,
          discountAmount,
          total,
          status,
          note: note ?? null,
          couponId: couponId ?? null,
          couponCode: couponCode ?? null,
          items: { createMany: { data: items } },
        },
        include: { items: true },
      });

      const payment = await dbTx.payment.create({
        data: {
          orderId: order.id,
          method: paymentMethod,
          status: paymentStatus,
          amount: total,
          transferContent: transferContent ?? null,
        },
      });

      return { order, payment };
    };

    if (tx) return run(tx);
    return prisma.$transaction(async (dbTx) => run(dbTx));
  },

  findById: async (id) =>
    withAddressShape(
      await prisma.order.findUnique({ where: { id }, include: ORDER_INCLUDE }),
    ),

  findByIdAndUser: async (id, userId) =>
    withAddressShape(
      await prisma.order.findFirst({
        where: { id, userId },
        include: ORDER_INCLUDE,
      }),
    ),

  findByIdempotencyKey: async (userId, idempotencyKey) =>
    prisma.order.findUnique({
      where: { userId_idempotencyKey: { userId, idempotencyKey } },
    }),

  findByUser: async (userId, { page, limit, status }) => {
    const where = { userId };
    if (status) where.status = status;
    const [orders, total] = await Promise.all([
      prisma.order.findMany({
        where,
        skip: (page - 1) * limit,
        take: limit,
        orderBy: { createdAt: "desc" },
        include: ORDER_LIST_INCLUDE,
      }),
      prisma.order.count({ where }),
    ]);
    return [orders.map(withAddressShape), total];
  },

  findAll: async (filters) => {
    const { page, limit, sortBy, sortOrder = "desc" } = filters;
    const where = buildAdminWhere(filters);
    const orderBy = sortBy
      ? [
          sortBy === "customerName"
            ? { user: { name: sortOrder } }
            : { total: sortOrder },
          { createdAt: "desc" },
          { id: "desc" },
        ]
      : [{ createdAt: "desc" }, { id: "desc" }];
    const startedAt = performance.now();
    const [orders, total] = await Promise.all([
      prisma.order.findMany({
        where,
        skip: (page - 1) * limit,
        take: limit,
        orderBy,
        select: ADMIN_ORDER_SELECT,
      }),
      prisma.order.count({ where }),
    ]);
    if (filters.search) {
      logger.info(
        {
          durationMs: Math.round(performance.now() - startedAt),
          resultCount: total,
        },
        "Admin order search completed",
      );
    }
    return [orders.map(withAdminListShape), total];
  },

  findSelected: async (ids, { forExport = false } = {}) => {
    const orders = await prisma.order.findMany({
      where: { id: { in: ids } },
      select: {
        ...ADMIN_ORDER_SELECT,
        // why: CSV does not need return eligibility; omit that relation query
        // and payment amounts for every export batch.
        ...(forExport && {
          returnRequests: false,
          payment: { select: { method: true, status: true } },
        }),
      },
    });
    const byId = new Map(orders.map((order) => [order.id, order]));
    return ids
      .filter((id) => byId.has(id))
      .map((id) => withAdminListShape(byId.get(id)));
  },

  countSelected: (ids) => prisma.order.count({ where: { id: { in: ids } } }),

  findAdminExportBatch: (filters, cursorId, batchSize = 500) =>
    prisma.order.findMany({
      where: buildAdminWhere(filters),
      ...(cursorId && { cursor: { id: cursorId }, skip: 1 }),
      take: batchSize,
      orderBy: [{ createdAt: "desc" }, { id: "desc" }],
      select: {
        id: true,
        createdAt: true,
        status: true,
        subtotal: true,
        shippingFee: true,
        discountAmount: true,
        total: true,
        shippingCarrier: true,
        trackingNumber: true,
        trackingUrl: true,
        user: { select: { name: true, email: true } },
        payment: {
          select: { method: true, status: true, refundedAmount: true },
        },
        _count: { select: { items: true } },
      },
    }),

  getAdminMetrics: async (filters) => {
    const where = buildAdminWhere(filters);
    const paidPaymentWhere = {
      status: { in: ["COMPLETED", "PARTIALLY_REFUNDED", "REFUNDED"] },
      order: { is: where },
    };
    const [
      statusGroups,
      paymentTotals,
      refundedOrders,
      itemTotals,
      overdueOrderCount,
    ] = await Promise.all([
      prisma.order.groupBy({
        by: ["status"],
        where,
        _count: { _all: true },
      }),
      prisma.payment.aggregate({
        where: paidPaymentWhere,
        _sum: { amount: true, refundedAmount: true },
        _count: { _all: true },
      }),
      prisma.payment.count({
        where: { ...paidPaymentWhere, refundedAmount: { gt: 0 } },
      }),
      prisma.orderItem.aggregate({
        where: { order: { is: where } },
        _sum: { quantity: true },
      }),
      prisma.order.count({
        where: buildAdminWhere({ ...filters, overdue: true }),
      }),
    ]);

    const groupedCounts = new Map(
      statusGroups.map((group) => [group.status, group._count._all]),
    );
    const statusCounts = Object.fromEntries(
      ORDER_STATUSES.map((orderStatus) => [
        orderStatus,
        groupedCounts.get(orderStatus) ?? 0,
      ]),
    );
    const totalOrders = statusGroups.reduce(
      (total, group) => total + group._count._all,
      0,
    );
    const grossRevenue = Number(paymentTotals._sum.amount ?? 0);
    const refundedAmount = Number(paymentTotals._sum.refundedAmount ?? 0);
    const paidOrderCount = paymentTotals._count._all;
    const cancelledOrders = statusCounts.CANCELLED ?? 0;
    const fulfillmentDistribution = Object.fromEntries(
      ["PROCESSING", "SHIPPED", "OUT_FOR_DELIVERY", "DELIVERED"].map(
        (orderStatus) => [orderStatus, statusCounts[orderStatus] ?? 0],
      ),
    );

    return {
      totalOrders,
      statusCounts,
      paidOrderCount,
      // NOTE: conversion here is payment conversion, not visitor/session conversion.
      paymentConversionRate: totalOrders
        ? Math.round((paidOrderCount / totalOrders) * 100)
        : 0,
      collectedRevenue: grossRevenue,
      refundedAmount,
      netRevenue: grossRevenue - refundedAmount,
      averageOrderValue: paymentTotals._count._all
        ? grossRevenue / paymentTotals._count._all
        : 0,
      cancellationRate: totalOrders
        ? Math.round((cancelledOrders / totalOrders) * 100)
        : 0,
      refundRate: paidOrderCount
        ? Math.round((refundedOrders / paidOrderCount) * 100)
        : 0,
      fulfillmentDistribution,
      overdueOrderCount,
      definitions: {
        collectedRevenue:
          "Original payment amount collected from orders with completed payment, including later-refunded orders",
        refundedAmount:
          "Total amount recorded as refunded against those payments",
        netRevenue: "Collected revenue minus recorded refunds",
        averageOrderValue:
          "Collected revenue divided by orders with completed or refunded payment",
        paymentConversionRate:
          "Paid orders divided by all orders created in the selected date range",
        cancellationRate:
          "Cancelled orders divided by all orders created in the selected date range",
        refundRate:
          "Paid orders with any refunded amount divided by paid orders",
        averageItems:
          "Total item quantities divided by all matching orders, including cancelled orders",
        overdueOrderCount: `Time in the current status exceeds ${ORDER_SLA_HOURS.payment}h before payment, ${ORDER_SLA_HOURS.fulfillment}h in fulfillment, or ${ORDER_SLA_HOURS.delivery}h in delivery`,
      },
      averageItems: totalOrders
        ? Number(itemTotals._sum.quantity ?? 0) / totalOrders
        : 0,
    };
  },

  findAdminById: async (id) =>
    withAddressShape(
      await prisma.order.findUnique({
        where: { id },
        include: {
          ...ORDER_INCLUDE,
          user: { select: { id: true, name: true, email: true } },
          _count: { select: { statusHistory: true } },
          statusHistory: {
            orderBy: { createdAt: "desc" },
            take: 100,
            include: {
              changedBy: { select: { id: true, name: true, role: true } },
            },
          },
          refunds: {
            orderBy: { createdAt: "desc" },
            take: 100,
            include: {
              approvedByUser: { select: { id: true, name: true, role: true } },
            },
          },
          returnRequests: {
            orderBy: { createdAt: "desc" },
            include: {
              inspector: { select: { id: true, name: true, role: true } },
              items: { include: { orderItem: true } },
            },
          },
        },
      }),
    ),

  updateShipping: (id, data) => prisma.order.update({ where: { id }, data }),

  getSpendStats: async (userId) => {
    const result = await prisma.payment.aggregate({
      where: {
        status: { in: ["COMPLETED", "PARTIALLY_REFUNDED"] },
        order: { is: { userId, status: { in: SPENT_STATUSES } } },
      },
      _sum: { amount: true, refundedAmount: true },
      _count: { _all: true },
    });
    return {
      count: result._count._all,
      totalSpent:
        Number(result._sum.amount ?? 0) -
        Number(result._sum.refundedAmount ?? 0),
    };
  },
};
